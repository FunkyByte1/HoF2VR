#!/usr/bin/env python3
"""Build the swing atlas (src/HoF2VR/Game/SwingAtlasData.cs) from the swing traces of the fixtures.

  swing_atlas.py [TSV ...]        (default: testdata/probes/A*_*.tsv and V*_*.tsv: the atlas and verification runs)

Each trace row (Game/SwingTrace.cs, scripts/swing_probe.py) holds one enemy blow at its impact: the striking part's ends
(root_a, root_b) and its motion (root_vel) in the attacker's own frame, and how far its root moved since the telegraph
(root_move). Per attacker model and attack clip: the per-coordinate median over its rows (rows whose striking part moved
less than 0.3 m against the body in the last 0.35 s are dropped: a part caught at rest is not the blow). The model's scale
(column `scale`, 1 when absent) is divided out. Decisions.md's pre-compute rule: the game looks these up during play.
"""
import csv
import glob
import os
import statistics
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hof2env  # noqa: E402

H = hof2env.H
OUT = H + "/src/HoF2VR/Game/SwingAtlasData.cs"


def vec(s):
    return [float(x) for x in s.split(",")]


def seg_point_xz(a, b, p):
    """Horizontal distance from point p (x, z) to the segment a-b (x, y, z), heights ignored."""
    ax, az, bx, bz = a[0], a[2], b[0], b[2]
    dx, dz = bx - ax, bz - az
    ll = dx * dx + dz * dz
    t = 0.0 if ll < 1e-9 else max(0.0, min(1.0, ((p[0] - ax) * dx + (p[1] - az) * dz) / ll))
    cx, cz = ax + dx * t, az + dz * t
    return ((p[0] - cx) ** 2 + (p[1] - cz) ** 2) ** 0.5


def main(paths):
    if not paths:
        paths = sorted(glob.glob(H + "/testdata/probes/A*_*.tsv") + glob.glob(H + "/testdata/probes/V*_*.tsv"))
    groups = {}
    for p in paths:
        with open(p) as f:
            for r in csv.DictReader(f, delimiter="\t"):
                try:
                    motion = float(r["part"].rsplit("@", 1)[1]) if "@" in r["part"] else 1.0
                except ValueError:
                    motion = 1.0
                if motion < 0.3 or not r.get("clip") or r["clip"] in ("-", "?") or r.get("pass_dt") is None or float(r.get("pass", "-1")) < 0:
                    continue
                # a shield or a foot as the striking part came from the probe build that ranked them like weapons (V1)
                if r["part"].startswith("foot:") or "shield" in r["part"].lower():
                    continue
                key = (r["enemy"], r["clip"], "%.2f" % float(r["clip_event"]))
                # the pass measured flat: the blade's segment (root frame) against the guard point 0.35 m in front of the
                # player's eyes, the player straight ahead of the attacker at hero_dist (the attackers face the hero)
                ra, rb, hd = vec(r["root_a"]), vec(r["root_b"]), float(r["hero_dist"])
                reach = seg_point_xz(ra, rb, (0.0, hd - 0.35))
                # root_* are divided by the model's scale already (SwingAtlas.Track.Measure)
                groups.setdefault(key, []).append([vec(r[k]) for k in ("root_a", "root_b", "root_vel", "root_move")] + [[float(r["pass_dt"]), float(r["pass"]), reach]])
    lines = []
    for (model, clip, ev), rows in sorted(groups.items()):
        med = [[statistics.median(row[k][i] for row in rows) for i in range(3)] for k in range(5)]
        v3 = lambda x: "new Vector3(%sf, %sf, %sf)" % tuple(("%.3f" % c) for c in x)
        lines.append('            new E("%s", "%s", %sf, %s, %s, %s, %s, %.3ff, %.3ff, %.3ff, %d),' % (model, clip, ev, v3(med[0]), v3(med[1]), v3(med[2]), v3(med[3]), med[4][0], med[4][1], med[4][2], len(rows)))
    src = '''using UnityEngine;

namespace HoF2VR
{
    /// GENERATED by scripts/swing_atlas.py from the fixtures' swing traces (testdata/probes/A*_*.tsv, V*_*.tsv): per attacker
    /// model, attack clip and hit event, where its blade passes the guard zone in the attacker's frame (SwingAtlas). Do not
    /// edit by hand.
    internal static class SwingAtlasData
    {
        public sealed class E
        {
            public readonly string Model, Clip;
            public readonly float Event, Dt, Pass, Reach;
            public readonly Vector3 A, B, V, Move;
            public readonly int N;
            public E(string model, string clip, float ev, Vector3 a, Vector3 b, Vector3 v, Vector3 move, float dt, float pass, float reach, int n) { Model = model; Clip = clip; Event = ev; A = a; B = b; V = v; Move = move; Dt = dt; Pass = pass; Reach = reach; N = n; }
        }

        public static readonly E[] Entries =
        {
%s
        };
    }
}
''' % "\n".join(lines)
    with open(OUT, "w") as f:
        f.write(src)
    print("%d shapes from %d rows in %d files -> %s" % (len(lines), sum(len(v) for v in groups.values()), len(paths), OUT))


if __name__ == "__main__":
    main(sys.argv[1:])
